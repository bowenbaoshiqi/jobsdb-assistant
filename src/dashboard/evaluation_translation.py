"""Chinese presentation projection for immutable Career Ops evaluations."""

from __future__ import annotations

import json
import re
from pathlib import Path

from src.domain.evaluation import JobEvaluation, NativeDimension

DIMENSION_TITLES = {
    "A": "职位与求职目标匹配度",
    "B": "简历匹配度",
    "C": "职级与申请策略",
    "D": "薪酬与市场需求",
    "E": "公司文化与组织条件",
    "F": "风险与阻碍",
}

RECOMMENDATIONS = {
    "strong_apply": "强烈建议申请",
    "apply": "建议申请",
    "Apply": "建议申请",
    "selective_apply": "建议谨慎申请，并先确认关键条件",
    "Consider": "建议谨慎申请，并先确认关键条件",
    "do_not_apply": "不建议申请",
    "Skip": "不建议申请",
}

_CHINESE = re.compile(r"[\u3400-\u9fff]")


class EvaluationTranslationCatalog:
    """Exact translations generated by the Agent without changing source data."""

    def __init__(
        self,
        translations: dict[str, str] | None = None,
        *,
        evaluation_overrides: dict[str, dict] | None = None,
    ) -> None:
        self.translations = translations or {}
        self.evaluation_overrides = evaluation_overrides or {}

    @classmethod
    def from_path(cls, path: Path) -> EvaluationTranslationCatalog:
        if not path.exists():
            return cls()
        payload = json.loads(path.read_text(encoding="utf-8"))
        translations = payload.get("translations", {})
        if not isinstance(translations, dict):
            raise ValueError("evaluation translation catalog must be an object")
        return cls(
            {
                str(source): str(target)
                for source, target in translations.items()
            },
            evaluation_overrides=payload.get("evaluations", {}),
        )

    def text(self, value: str) -> str:
        if not value or _CHINESE.search(value):
            return value
        return self.translations.get(value, f"原文：{value}")

    def list(self, values: list[str]) -> list[str]:
        return [self.text(value) for value in values]

    def override(self, evaluation_id: str) -> dict:
        return self.evaluation_overrides.get(evaluation_id, {})


def translate_evaluation(
    evaluation: JobEvaluation,
    catalog: EvaluationTranslationCatalog,
) -> JobEvaluation:
    """Return a Chinese Dashboard copy while preserving the native record."""

    override = catalog.override(evaluation.id)
    dimension_overrides = override.get("dimensions", {})
    dimensions = [
        NativeDimension(
            code=dimension.code,
            title=DIMENSION_TITLES[dimension.code],
            score=dimension.score,
            findings=dimension_overrides.get(
                dimension.code,
                {},
            ).get("findings", catalog.list(dimension.findings)),
            evidence=dimension_overrides.get(
                dimension.code,
                {},
            ).get("evidence", catalog.list(dimension.evidence)),
        )
        for dimension in evaluation.dimensions
    ]
    recommendation = override.get(
        "recommendation",
        RECOMMENDATIONS.get(
            evaluation.recommendation,
            catalog.text(evaluation.recommendation),
        ),
    )
    return evaluation.model_copy(
        update={
            "dimensions": dimensions,
            "recommendation": recommendation,
            "strengths": override.get(
                "strengths",
                catalog.list(evaluation.strengths),
            ),
            "gaps": override.get("gaps", catalog.list(evaluation.gaps)),
            "risks": override.get("risks", catalog.list(evaluation.risks)),
            "evidence": catalog.list(evaluation.evidence),
        }
    )
